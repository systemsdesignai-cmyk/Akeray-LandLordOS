export function tFormat(
  template: string,
  params: Record<string, string | number>
): string {
  return Object.entries(params).reduce(
    (acc, [key, val]) => acc.replace(new RegExp(`\\{${key}\\}`, 'g'), String(val)),
    template
  );
}


